import type { ScenarioBundle } from "../types";

type Props = {
  scenario: ScenarioBundle;
};

/**
 * Renders the bundle's provenance block.
 *
 * The workshop abstract claims the datasets are "biologically informed simulated datasets
 * calibrated to real-world ancestry distributions, allele frequencies, and effect sizes."
 * For an ELSI-tracked session pitched to a methods audience, that is the claim most likely
 * to be challenged from the floor. The generator already records exactly which inputs are
 * real and which are invented; showing it turns an assertion into something a participant
 * can check, and makes the real/synthetic boundary part of the teaching rather than a
 * caveat buried in a JSON file.
 *
 * Collapsed by default so it does not compete with the module's charts.
 */
export function ProvenancePanel({ scenario }: Props) {
  const { provenance, variant } = scenario;
  const referenceFrequencies = provenance.realInputs?.alleleFrequencies ?? [];
  const ancestryDistribution = provenance.realInputs?.ancestryDistribution;

  return (
    <details className="provenance-panel">
      <summary>
        <span>How these numbers were produced</span>
        <span className="provenance-seed">seed {provenance.seed}</span>
      </summary>

      <div className="provenance-body">
        {variant && (
          <section>
            <h3>Variant</h3>
            <dl className="provenance-facts">
              <div>
                <dt>Marker</dt>
                <dd>{variant.rsid}</dd>
              </div>
              <div>
                <dt>Gene</dt>
                <dd>{variant.gene}</dd>
              </div>
              <div>
                <dt>Locus</dt>
                <dd>{variant.locus}</dd>
              </div>
              <div>
                <dt>Trait</dt>
                <dd>{variant.trait}</dd>
              </div>
            </dl>
          </section>
        )}

        <section>
          <h3>Real inputs</h3>
          {referenceFrequencies.length > 0 && (
            <ul>
              {referenceFrequencies.map((frequency) => (
                <li key={frequency.rsid}>
                  <strong>{frequency.rsid}</strong> ({frequency.gene}, {frequency.locus}) —
                  allele frequencies from {frequency.source}. {frequency.note}
                </li>
              ))}
            </ul>
          )}
          {ancestryDistribution && <p>Ancestry composition: {ancestryDistribution}</p>}
          {referenceFrequencies.length === 0 && !ancestryDistribution && (
            <p>This module derives from stated assumptions rather than reference datasets.</p>
          )}
        </section>

        <section>
          <h3>Synthetic inputs</h3>
          <ul>
            {provenance.syntheticInputs.map((input) => (
              <li key={input}>{input}</li>
            ))}
          </ul>
        </section>

        <section>
          <h3>Assumptions</h3>
          <ul>
            {provenance.assumptions.map((assumption) => (
              <li key={assumption}>{assumption}</li>
            ))}
          </ul>
        </section>

        <section>
          <h3>How the displayed values were computed</h3>
          <p>{provenance.derived}</p>
          <p className="provenance-generator">
            Generated by <code>{provenance.generator}</code> v{provenance.generatorVersion},
            seed {provenance.seed}, alpha {provenance.alpha}. Nothing shown in this module is
            hand-entered; re-running the generator reproduces every number exactly.
          </p>
        </section>
      </div>
    </details>
  );
}
